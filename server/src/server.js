import express from 'express';
import cors from 'cors';
import archiver from 'archiver';
import { Readable } from 'node:stream';
import { NoCatchExtractor, sanitizeFilename } from '@lorapok/nocatch-core';

const app = express();
const PORT = process.env.PORT || 3890;

app.use(cors());
app.use(express.json());

// Health Check
app.get('/api/health', (req, res) => {
  res.json({
    status: 'online',
    product: 'NoCatch by Lorapok Labs',
    service: 'Google NotebookLM Harvester API',
    version: '1.0.0',
    timestamp: new Date().toISOString(),
  });
});

// Single Extract Endpoint
app.post('/api/extract', async (req, res) => {
  const { url, cookie } = req.body;
  if (!url) {
    return res.status(400).json({ error: 'Missing required "url" parameter in request body.' });
  }

  try {
    const extractor = new NoCatchExtractor({ cookie });
    const result = await extractor.extract(url);
    res.json({
      success: true,
      data: result,
    });
  } catch (err) {
    res.status(500).json({
      success: false,
      error: err.message,
    });
  }
});

// Batch Extract Endpoint
app.post('/api/batch', async (req, res) => {
  const { urls, cookie } = req.body;
  if (!Array.isArray(urls) || urls.length === 0) {
    return res.status(400).json({ error: 'Array of "urls" is required in request body.' });
  }

  const extractor = new NoCatchExtractor({ cookie });
  const results = [];

  for (const url of urls) {
    try {
      const data = await extractor.extract(url);
      results.push({ url, success: true, data });
    } catch (err) {
      results.push({ url, success: false, error: err.message });
    }
  }

  res.json({
    success: true,
    total: urls.length,
    results,
  });
});

// Direct Download Proxy (Streams audio with Content-Disposition)
app.get('/api/download', async (req, res) => {
  const { url, filename } = req.query;
  if (!url) {
    return res.status(400).send('Missing "url" parameter');
  }

  try {
    const streamRes = await fetch(url, {
      headers: {
        'User-Agent':
          'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36',
      },
    });

    if (!streamRes.ok) {
      return res.status(streamRes.status).send(`Failed to stream from source: ${streamRes.statusText}`);
    }

    const cleanFilename = sanitizeFilename(filename || 'notebooklm_audio.m4a');
    res.setHeader('Content-Disposition', `attachment; filename="${cleanFilename}"`);
    res.setHeader('Content-Type', streamRes.headers.get('content-type') || 'audio/mp4');

    const contentLength = streamRes.headers.get('content-length');
    if (contentLength) {
      res.setHeader('Content-Length', contentLength);
    }

    const nodeStream = Readable.fromWeb(streamRes.body);
    nodeStream.pipe(res);
  } catch (err) {
    res.status(500).send(`Streaming error: ${err.message}`);
  }
});

// Bundle ZIP Endpoint (Downloads audio + writes notes/metadata to ZIP)
app.post('/api/bundle', async (req, res) => {
  const { url, cookie } = req.body;
  if (!url) {
    return res.status(400).json({ error: 'Missing required "url" parameter.' });
  }

  try {
    const extractor = new NoCatchExtractor({ cookie });
    const data = await extractor.extract(url);

    const zipFilename = sanitizeFilename(`${data.title}_NoCatch_Bundle.zip`);
    res.setHeader('Content-Disposition', `attachment; filename="${zipFilename}"`);
    res.setHeader('Content-Type', 'application/zip');

    const archive = archiver('zip', { zlib: { level: 9 } });
    archive.pipe(res);

    // 1. Add metadata JSON
    archive.append(JSON.stringify(data, null, 2), { name: 'metadata.json' });

    // 2. Add Readme / Summary Markdown
    const summaryMd = `# ${data.title}
Generated by Google NotebookLM | Harvested by NoCatch (Lorapok Labs)
Date: ${data.extractedAt}
Canonical URL: ${data.canonicalUrl}

## Overview
- Sources Analyzed: ${data.sourceCount}
- Audio Overview Title: ${data.audio ? data.audio.episodeName : 'None'}
- Audio Duration: ${data.audio ? data.audio.durationFormatted : 'N/A'}
- Quality: ${data.audio ? data.audio.quality : 'N/A'}

---
*Powered by NoCatch & Loragent — Lorapok Labs*
https://nocatch.lorapok.tech
`;
    archive.append(summaryMd, { name: 'OVERVIEW.md' });

    // 3. Add text content if present
    if (data.textContent) {
      archive.append(data.textContent, { name: 'notes.md' });
    }

    // 4. Download and stream audio into zip if present
    if (data.audio) {
      const audioUrl = data.audio.directDownloadUrl || data.audio.primaryStreamUrl;
      const audioRes = await fetch(audioUrl, {
        headers: {
          'User-Agent':
            'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36',
        },
      });

      if (audioRes.ok) {
        const audioNodeStream = Readable.fromWeb(audioRes.body);
        archive.append(audioNodeStream, { name: data.audio.filename });
      }
    }

    await archive.finalize();
  } catch (err) {
    if (!res.headersSent) {
      res.status(500).json({ error: err.message });
    }
  }
});

app.listen(PORT, () => {
  console.log(`⚡ [NoCatch Server] Active on port ${PORT}`);
  console.log(`   Health: http://localhost:${PORT}/api/health`);
  console.log(`   Host Target: nocatch.lorapok.tech`);
});
